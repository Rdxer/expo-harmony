/**
 * 通用帧解析器接口：把 TCP 字节流切分成完整帧。
 *
 * 实现类内部维护待续缓冲，天然支持分包（一帧拆多次到达）与粘包（多帧一次到达）。
 */
export interface FrameParser {
  /**
   * 输入一个原始字节片段，返回本次新解析出的完整帧数组（帧内字节拷贝自内部缓冲）。
   * 数据不足构成完整帧时返回空数组，未消费的字节保留在内部缓冲中等待续传。
   */
  push(chunk: Uint8Array): Uint8Array[];
  /** 清空内部待续缓冲，从下一个字节重新开始帧同步。 */
  reset(): void;
}
